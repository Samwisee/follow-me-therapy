// Build the design system's live component bundle.
//   npm install && npm run design-system
// Reads  design/design-system/project/components/src/*.tsx and img/brand/*.svg
// Writes components/src/logo.ts (generated), components/bundle.js (one classic
// script that sets window.FollowMeTherapy and uses window.React / ReactDOM).
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const COMP = join(ROOT, 'design/design-system/project/components');

// 1. Logo: the ink files, recoloured to currentColor so the component sets the colour.
const logo = {};
for (const [key, file] of [['mark', 'mark'], ['stacked', 'lockup-stacked'], ['horizontal', 'lockup-horizontal']]) {
  const svg = readFileSync(join(ROOT, `img/brand/follow-me-therapy-${file}.svg`), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<title>[\s\S]*?<\/title>/, '')
    .replace(/fill="#[0-9a-fA-F]{3,8}"/g, 'fill="currentColor"');
  logo[key] = { viewBox, body };
}
writeFileSync(join(COMP, 'src/logo.ts'), '// GENERATED by tools/build_design_system.mjs from img/brand/*.svg\nexport const LOGO = ' + JSON.stringify(logo) + ' as const;\n');

// 2. Bundle, with react / react-dom resolved to the page's globals.
const globals = {
  name: 'globals', setup(b) {
    b.onResolve({ filter: /^react(-dom)?(\/.*)?$/ }, a => ({ path: a.path, namespace: 'g' }));
    b.onLoad({ filter: /.*/, namespace: 'g' }, a => ({
      contents: a.path.startsWith('react-dom') ? 'module.exports = window.ReactDOM'
        : a.path === 'react/jsx-runtime' ? 'const R=window.React;module.exports={jsx:(t,p,k)=>R.createElement(t,k===undefined?p:{...p,key:k}),jsxs:(t,p,k)=>R.createElement(t,k===undefined?p:{...p,key:k}),Fragment:R.Fragment}'
        : 'module.exports = window.React', loader: 'js' }));
  } };
const res = await build({ entryPoints: [join(COMP, 'src/index.tsx')], bundle: true, format: 'iife', globalName: 'FollowMeTherapy',
  minify: true, write: false, jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' }, plugins: [globals], target: 'es2019', charset: 'utf8' });
let js = res.outputFiles[0].text;
const names = [...readFileSync(join(COMP, 'src/index.tsx'), 'utf8').matchAll(/^export function (\w+)/gm)].map(m => m[1]);
const header = `/* @ds-bundle: ${JSON.stringify({ format: 4, namespace: 'FollowMeTherapy', components: names.map(name => ({ name })) })} */\n`;
js = js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '\\x3C!--');
writeFileSync(join(COMP, 'bundle.js'), header + js + '\nwindow.FollowMeTherapy = FollowMeTherapy;\n');
console.log(`bundle.js: ${names.length} components, ${(js.length / 1024).toFixed(0)} KB`);
